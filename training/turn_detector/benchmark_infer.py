"""Frozen, resumable, audio-only TurnBench inference. Run only on Colab.

The freeze operation reads code/weights but never benchmark data. Test runs emit
only official event predictions; optional probability caches are dev-only.

--decision-phase-ms 128 requires a full phase128 training manifest and the shared
phase128_full_arrays helper. It extracts the real complete 128+160*k ms grid
from source-duration-floor audio, including naturally observed tail decisions.
It never shifts predictions or pads a final decision. Before a real benchmark
run, qualify the shared helper and phase encoder (including batched extraction)
with qualify_phase128_benchmark.py in the same immutable bundle/runtime. Supply
its report with --phase-qualification. Missing or changed runtime evidence fails
before benchmark data is opened. Source-only tests are not runtime qualification.
"""
from pathlib import Path
import argparse
import hashlib
import importlib.metadata
import io
import json
import os
import platform
import re
import sys
import numpy as np

MODEL_REPO = 'nvidia/parakeet_realtime_eou_120m-v1'
MODEL_REVISION = 'a7e2b4629593dce0ec19f600e00e9904353fda2d'
MODEL_FILE = 'parakeet_realtime_eou_120m-v1.nemo'
REVISIONS = {'dev': '8fa18a24be51528a45397b35cbcaecd84202062b',
             'test': '0c12a77a0134449757e4fd4144913bfcff0c376d'}
ROOT = Path(__file__).resolve().parent


def sha(path):
    digest = hashlib.sha256()
    with Path(path).open('rb') as file:
        for block in iter(lambda: file.read(1024 * 1024), b''):
            digest.update(block)
    return digest.hexdigest()


def digest(value):
    return hashlib.sha256(json.dumps(value, sort_keys=True, allow_nan=False).encode()).hexdigest()


def require_equal(saved, current, what):
    if saved != current:
        raise ValueError(what + ' changed; create a new explicitly frozen run')


def model_kind(state):
    if state.get('format') == 'equal-probability-turn-heads-v1':
        return 'ensemble'
    if state.get('config', {}).get('model') == 'projection-GRU-EOT':
        if state['config'].get('bidirectional') is not False:
            raise ValueError('Only causal GRU artifacts are permitted')
        return 'gru'
    if 'auxiliary' in state and 'model' in state:
        return 'mlp'
    raise ValueError('Unrecognized head artifact')


def predictor(state, device):
    kind = model_kind(state)
    if kind == 'ensemble':
        from ensemble_heads import EnsemblePredictor
        return EnsemblePredictor(state, device).predict
    from heads import make_model, predict
    from temporal_head import make_temporal_model, temporal_predict
    if kind == 'mlp':
        model = make_model(state['dim'], state['hidden'], state['auxiliary'])
    else:
        model = make_temporal_model(state['dim'], state['hidden'], state['projection'], state['dropout'])
    model.load_state_dict(state['model'], strict=True)
    model.to(device).eval()
    if kind == 'mlp':
        return lambda records: predict(model, records, state['mean'], state['std'], device)
    return lambda records: temporal_predict(model, records, state['mean'], state['std'], device,
                                            state['config']['chunk_frames'])


def source_lock(upstream):
    # Conservative superset: also catches newly introduced helper dependencies.
    return {prefix + '/' + str(p.relative_to(root)): sha(p)
            for prefix, root in [('experiment', ROOT), ('turnbench', Path(upstream) / 'turnbench')]
            for p in sorted(root.rglob('*.py'))}


def dependency_lock():
    """Hash all recorded installed package files, excluding generated bytecode.

    This costs an initial sequential disk read, deliberately paid for strict
    freeze/resume identity. No package imports/downloads are performed here.
    """
    result = {}
    for distribution in importlib.metadata.distributions():
        name = re.sub(r'[-_.]+', '-', distribution.metadata['Name']).lower()
        files = {}
        for entry in distribution.files or []:
            path = Path(distribution.locate_file(entry))
            if path.is_file() and path.suffix != '.pyc':
                files[str(entry)] = sha(path)
        value = {'origin': str(Path(distribution.locate_file('')).resolve()),
                 'version': distribution.version, 'files': digest(files)}
        # Colab can legitimately expose several metadata records for one package.
        # Preserve every record, including identical duplicates, and fingerprint
        # import precedence separately rather than guessing the winning variant.
        result.setdefault(name, []).append(value)
    for entries in result.values():
        entries.sort(key=lambda value: json.dumps(value, sort_keys=True))
    return {'python': platform.python_version(), 'packages': result,
            'import_path': [{'entry': entry, 'resolved': str(Path(entry or os.getcwd()).resolve())}
                            for entry in sys.path]}


def operating_point(value):
    threshold = float(value['threshold'])
    recommit = value['recommit_s']
    if not np.isfinite(threshold) or not 0 <= threshold <= 1 or recommit not in (None, 1.5):
        raise ValueError('Invalid frozen operating point')
    return {'threshold': threshold, 'recommit_s': recommit}


def verify_continued(args, state):
    if not args.encoder_checkpoint:
        if args.encoder_identity or args.encoder_causality:
            raise ValueError('Encoder evidence requires a continued checkpoint')
        return None, None
    if not args.encoder_identity or not args.encoder_causality:
        raise ValueError('Continued encoder requires identity and synthetic causality evidence')
    import torch
    from cache_identity import validate_continuation
    identity = json.loads(Path(args.encoder_identity).read_text())
    evidence = json.loads(Path(args.encoder_causality).read_text())
    checkpoint_hash = sha(args.encoder_checkpoint)
    continuation = torch.load(args.encoder_checkpoint, map_location='cpu', weights_only=False)
    require_equal(checkpoint_hash, sha(args.encoder_checkpoint), 'Encoder during load')
    require_equal(identity['encoder_checkpoint_sha256'], checkpoint_hash, 'Encoder identity')
    require_equal(identity['base_model_repo'], MODEL_REPO, 'Base model repo')
    require_equal(identity['base_model_revision'], MODEL_REVISION, 'Base model revision')
    validate_continuation(continuation, continuation['audit'], sha(ROOT / 'continue_vap.py'), MODEL_REPO, MODEL_REVISION)
    require_equal(identity['encoder_checkpoint_update'], continuation['update'], 'Encoder update')
    require_equal(identity['continuation_recipe_sha256'],
                  hashlib.sha256(json.dumps(continuation['recipe'], sort_keys=True).encode()).hexdigest(), 'Encoder recipe')
    if evidence.get('encoder_checkpoint_sha256') != checkpoint_hash or evidence.get('synthetic_only') is not True:
        raise ValueError('Causality evidence does not identify this encoder')
    if len(evidence.get('checks', [])) < 3 or not all(c.get('passed') is True for c in evidence['checks']):
        raise ValueError('Encoder causality evidence incomplete')
    require_equal(identity['continuation_source_sha256'], continuation['source_sha256'], 'Continuation source')
    require_equal(identity['continuation_manifest_sha256'], continuation['audit']['manifest_sha256'], 'Continuation manifest')
    require_equal(identity['continuation_split_sha256'], continuation['audit']['split_sha256'], 'Continuation split')
    return continuation, {'checkpoint': checkpoint_hash, 'identity': sha(args.encoder_identity),
                          'causality': sha(args.encoder_causality)}


def resolve_audio_dataset(split, directory=None):
    """Upstream-compatible Arrow loading, with annotations NEVER projected.

    A Drive directory must contain exact pinned-revision parquet bytes. Verify
    against HF LFS metadata before opening a parquet table. No golden repo use.
    """
    from huggingface_hub import HfApi, snapshot_download
    import pyarrow as pa
    import pyarrow.parquet as pq
    source = 'mundo-ai/turn-benchmark-' + split
    revision = REVISIONS[split]
    info = HfApi().dataset_info(source, revision=revision, files_metadata=True)
    require_equal(info.sha, revision, 'Dataset revision')
    entries = [s for s in info.siblings if s.rfilename.endswith('.parquet')]
    if not entries:
        raise ValueError('Pinned dataset has no parquet shards')
    root = Path(directory or snapshot_download(source, repo_type='dataset', revision=revision, allow_patterns='*.parquet'))
    files = []
    for entry in sorted(entries, key=lambda e: e.rfilename):
        path = root / entry.rfilename
        lfs = entry.lfs
        expected = lfs.get('sha256') if isinstance(lfs, dict) else getattr(lfs, 'sha256', None)
        if not expected:
            raise ValueError('Parquet shard lacks verifiable LFS SHA256')
        require_equal(sha(path), expected, 'Dataset shard ' + entry.rfilename)
        files.append((path, expected))
    table = pa.concat_tables([pq.read_table(p, columns=['conversation_id', 'speaker_1_audio', 'speaker_2_audio'])
                              for p, _ in files])
    ids = [str(v) for v in table.column('conversation_id').to_pylist()]
    if len(set(ids)) != len(ids) or not all(v.isdecimal() for v in ids):
        raise ValueError('Invalid/duplicate conversation IDs')
    index = {cid: i for i, cid in enumerate(ids)}
    return table, index, {'source': source, 'revision': revision,
                          'shards': {str(p.relative_to(root)): h for p, h in files}}


def decode_audio(table, index, cid, decision_phase_ms=160):
    if decision_phase_ms not in (128, 160):
        raise ValueError('Unknown decision phase')
    import soundfile as sf
    from encoder import causal_resample
    channels = []
    hashes = []
    rates = []
    for speaker in (1, 2):
        value = table.column(f'speaker_{speaker}_audio')[index[cid]].as_py()
        payload = value['bytes']
        if not payload:
            raise ValueError('Embedded audio bytes required')
        wave, sr = sf.read(io.BytesIO(payload), dtype='float32', always_2d=False)
        if wave.ndim != 1 or not np.isfinite(wave).all():
            raise ValueError('Invalid mono audio')
        channels.append(wave); rates.append(sr); hashes.append(hashlib.sha256(payload).hexdigest())
    if rates[0] != rates[1] or len(channels[0]) != len(channels[1]):
        raise ValueError('Channel alignment mismatch')
    duration = len(channels[0]) / rates[0]
    wave, _ = causal_resample(np.stack(channels, axis=1), rates[0])
    # Resampling can round up; never permit a decision beyond source duration.
    max_samples = len(channels[0]) * 16000 // rates[0]
    wave = wave[:max_samples if decision_phase_ms == 128 else max_samples//2560*2560]
    if len(wave) < decision_phase_ms * 16:
        raise ValueError('Conversation shorter than decision frame')
    return wave, duration, hashes


def open_run(out, identity, resume):
    from checkpointing import atomic_text
    out = Path(out)
    if resume:
        require_equal(json.loads((out / 'inference.json').read_text()), identity, 'Resume identity')
    else:
        out.mkdir(parents=True, exist_ok=False)
        atomic_text(json.dumps(identity, sort_keys=True, indent=2), out / 'inference.json')
    (out / 'conversations').mkdir(exist_ok=True)
    return out


def validate_feature_export(split, dev_cache, dev_feature_cache):
    if dev_feature_cache and (split != 'dev' or not dev_cache):
        raise ValueError('Feature export requires public dev and --dev-cache')


def protocol_phase(protocol):
    start = protocol.get('grid_start_samples', 2560)
    contract = protocol.get('decision_phase_contract')
    if start == 2560 and contract is None:
        return 160
    if start == 2048 and contract == 'phase128-full-v1':
        return 128
    raise ValueError('Unknown decision phase contract')


def validate_manifest_phase(records, phase):
    if not records:
        raise ValueError('Empty head feature manifest')
    for row in records:
        contract = row.get('phase_grid_contract')
        if phase == 128:
            if contract != 'phase128-full-v1':
                raise ValueError('Full phase128 head feature manifest required')
        elif contract is not None or row.get('phase128') is not None:
            raise ValueError('Phase head cannot consume original decision grid')


def main():
    import torch
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument('--split', choices=['dev', 'test'], required=True)
    ap.add_argument('--checkpoint', required=True); ap.add_argument('--out')
    ap.add_argument('--feature-manifest', required=True, help='Metadata only; exact head training cache manifest')
    ap.add_argument('--freeze'); ap.add_argument('--freeze-out')
    ap.add_argument('--batch-size', type=int, default=4)
    ap.add_argument('--gate', choices=['mean', 'last'], default='mean')
    ap.add_argument('--decision-phase-ms', type=int, choices=[160, 128], default=160)
    ap.add_argument('--phase-qualification', help='Required synthetic runtime report for phase128 freeze/inference')
    ap.add_argument('--operating-point'); ap.add_argument('--base-model')
    ap.add_argument('--encoder-checkpoint'); ap.add_argument('--encoder-identity'); ap.add_argument('--encoder-causality')
    ap.add_argument('--dataset-dir'); ap.add_argument('--resume', action='store_true')
    ap.add_argument('--dev-cache', action='store_true')
    ap.add_argument('--dev-feature-cache', action='store_true', help='Dev-only immutable reusable encoder features; requires --dev-cache')
    ap.add_argument('--turnbench-path', default='/content/turnbench')
    args = ap.parse_args()
    if not Path('/content').is_dir() or not Path(args.turnbench_path, 'turnbench').is_dir():
        raise RuntimeError('Run on prepared Colab only')
    validate_feature_export(args.split,args.dev_cache,args.dev_feature_cache)
    if (args.decision_phase_ms == 128) != bool(args.phase_qualification):
        raise ValueError('Phase128 requires --phase-qualification; default160 must omit it')
    if args.batch_size < 1 or (args.split == 'test' and args.dev_cache):
        raise ValueError('Invalid batch size or forbidden test probability export')
    if args.freeze_out and (args.freeze or args.resume):
        raise ValueError('Freeze creation cannot resume or consume another freeze')
    if args.split == 'test' and not (args.freeze or args.freeze_out):
        raise ValueError('Test inference requires explicit freeze')
    if Path('/content/.hf_token').is_file():
        os.environ['HF_TOKEN'] = Path('/content/.hf_token').read_text().strip()
    os.environ['HF_HUB_DISABLE_PROGRESS_BARS'] = '1'
    torch.set_num_threads(2)
    sys.path.insert(0, args.turnbench_path)
    # Match initialized NeMo/Lhotse import precedence in every runtime snapshot.
    from nemo.collections.asr.models import ASRModel
    checkpoint_hash = sha(args.checkpoint)
    state = torch.load(args.checkpoint, map_location='cpu', weights_only=False)
    require_equal(checkpoint_hash, sha(args.checkpoint), 'Head during load')
    op = operating_point(json.loads(Path(args.operating_point).read_text()) if args.operating_point else state['operating_point'])
    continuation, continued_identity = verify_continued(args, state)
    manifest_hash = sha(args.feature_manifest)
    members = [m['checkpoint'] for m in state['members']] if model_kind(state) == 'ensemble' else [state]
    for member in members:
        require_equal(member['config']['manifest_sha256'], manifest_hash, 'Head feature manifest')
    records = json.loads(Path(args.feature_manifest).read_text())
    validate_manifest_phase(records, args.decision_phase_ms)
    expected_encoder = continued_identity['checkpoint'] if continued_identity else None
    if not records or any(r.get('encoder_checkpoint_sha256') != expected_encoder for r in records):
        raise ValueError('Head feature manifest encoder lineage mismatch')
    from huggingface_hub import hf_hub_download, HfApi
    base = Path(args.base_model or hf_hub_download(MODEL_REPO, MODEL_FILE, revision=MODEL_REVISION))
    model_info = HfApi().model_info(MODEL_REPO, revision=MODEL_REVISION, files_metadata=True)
    require_equal(model_info.sha, MODEL_REVISION, 'Base model revision')
    entry = next(e for e in model_info.siblings if e.rfilename == MODEL_FILE)
    lfs = entry.lfs
    expected_hash = lfs.get('sha256') if isinstance(lfs, dict) else getattr(lfs, 'sha256', None)
    if not expected_hash:
        raise ValueError('Base model lacks pinned artifact hash')
    require_equal(sha(base), expected_hash, 'Pinned base model bytes')
    from silero_vad import load_silero_vad
    import silero_vad
    vad_path = Path(silero_vad.__file__).parent / 'data' / 'silero_vad.jit'
    print(json.dumps({'stage': 'verifying_source_and_dependency_bytes', 'split': args.split}), flush=True)
    identity = {'format': 'turnbench-inference-freeze-v2', 'sources': source_lock(args.turnbench_path),
                'dependencies': dependency_lock(), 'checkpoint': checkpoint_hash, 'kind': model_kind(state),
                'feature_manifest': manifest_hash,
                'base_model': {'repo': MODEL_REPO, 'revision': MODEL_REVISION, 'sha256': sha(base)},
                'continued_encoder': continued_identity, 'silero_weights': sha(vad_path),
                'protocol': {'split': args.split, 'source': 'mundo-ai/turn-benchmark-'+args.split,
                             'revision': REVISIONS[args.split], 'gate': args.gate, 'history_vad': 'mean',
                             'grid_samples': 2560, 'sample_rate': 16000, 'feature_dtype': 'float16',
                             'batch_size': args.batch_size, 'operating_point': op, 'dev_cache': args.dev_cache,
                             'torch_threads': 2, 'device': torch.cuda.get_device_name(0),
                             'cuda': torch.version.cuda, 'cudnn': torch.backends.cudnn.version(),
                             'tf32_matmul': torch.backends.cuda.matmul.allow_tf32,
                             'tf32_cudnn': torch.backends.cudnn.allow_tf32}}
    if args.decision_phase_ms == 128:
        if not identity['sources'].get('experiment/phase128_full_arrays.py'):
            raise ValueError('Full phase128 helper missing from frozen sources')
        identity['protocol'].update(grid_start_samples=2048, decision_phase_contract='phase128-full-v1')
        from phase128_qualification import qualification_identity, validate_qualification
        qualification_hash = sha(args.phase_qualification)
        report = json.loads(Path(args.phase_qualification).read_text())
        require_equal(qualification_hash, sha(args.phase_qualification), 'Phase qualification during load')
        validate_qualification(report, qualification_identity(identity))
        identity['phase_qualification_sha256'] = qualification_hash
    if args.dev_feature_cache:
        identity['protocol']['dev_feature_cache'] = True
    if args.freeze_out:
        from checkpointing import atomic_text
        if Path(args.freeze_out).exists():
            raise ValueError('Refusing to overwrite freeze')
        atomic_text(json.dumps(identity, sort_keys=True, indent=2), args.freeze_out)
        print('FREEZE_WRITTEN_NO_DATA_LOADED', flush=True)
        return
    if args.freeze:
        require_equal(json.loads(Path(args.freeze).read_text()), identity, 'Frozen inference identity')
    if not args.out:
        raise ValueError('--out required for inference')
    # Validate resume identity before resolving/opening benchmark audio.
    if args.resume:
        saved = json.loads((Path(args.out) / 'inference.json').read_text())
        require_equal(saved['freeze'], identity, 'Resume freeze')
    print(json.dumps({'stage': 'verifying_dataset_shards', 'split': args.split}), flush=True)
    table, index, dataset_identity = resolve_audio_dataset(args.split, args.dataset_dir)
    ids = sorted(index, key=int)
    run_identity = {'freeze': identity, 'dataset': dataset_identity, 'ids': ids}
    out = open_run(args.out, run_identity, args.resume)
    run_hash = digest(run_identity)
    from checkpointing import atomic_text, _atomic_write
    from turnbench.submission import Submission, ConversationPrediction, SpeakerEvents, validate_coverage, validate_event_times
    from heads import speaker_features, causal_history, commit_events
    from encoder import ParakeetStreamingEncoder
    from vad_batch import causal_vad_batch
    saved_rows = {}
    for path in (out / 'conversations').glob('*.json'):
        row = json.loads(path.read_text())
        require_equal(row['identity'], run_hash, 'Conversation identity')
        require_equal(row['payload_sha256'], digest(row['payload']), 'Conversation payload')
        payload = row['payload']; cid = payload['prediction']['conversation_id']
        if cid not in index or path.stem != cid or cid in saved_rows:
            raise ValueError('Unknown/duplicate recovery conversation')
        prediction = ConversationPrediction.model_validate(payload['prediction'])
        validate_event_times(prediction, payload['duration_s'])
        if args.dev_cache:
            require_equal(payload['dev_cache_sha256'], sha(out / f'{cid}.npz'), 'Dev recovery cache')
        if args.dev_feature_cache:
            require_equal(payload['dev_features_sha256'], sha(out / f'{cid}.features.npz'), 'Dev feature recovery cache')
        saved_rows[cid] = payload
    encode = infer = detector = None
    for first in range(0, len(ids), args.batch_size):
        group = ids[first:first+args.batch_size]
        if all(cid in saved_rows for cid in group):
            continue
        if encode is None:
            print(json.dumps({'stage': 'loading_inference_models', 'split': args.split}), flush=True)
            from nemo.collections.asr.models import ASRModel
            model = ASRModel.restore_from(str(base), map_location='cpu')
            require_equal(identity['base_model']['sha256'], sha(base), 'Base encoder during load')
            if continuation is not None:
                model.encoder.load_state_dict(continuation['encoder'], strict=True)
            encode = ParakeetStreamingEncoder(model=model, device='cuda')
            infer = predictor(state, 'cuda'); detector = load_silero_vad()
            require_equal(identity['silero_weights'], sha(vad_path), 'Silero during load')
        print(json.dumps({'stage': 'inferring_batch', 'split': args.split, 'ids': group}), flush=True)
        decoded = [decode_audio(table, index, cid, args.decision_phase_ms) for cid in group]
        waves = [item[0] for item in decoded]
        if args.decision_phase_ms == 128:
            from phase128_full_arrays import native_silero_all, inputs_at_decisions
            ends = [np.arange(2048, len(wave)+1, 2560, dtype=np.int64) for wave in waves]
            seqs = encode.extract_batch(waves, decision_samples=ends)
            raw_vads = [native_silero_all(wave, detector=detector) for wave in waves]
        else:
            seqs = encode.extract_batch(waves)
            raw_vads = causal_vad_batch(waves, detector=detector, reduction='raw')
        for cid, wave, seq, raw, (_, duration, hashes) in zip(group, waves, seqs, raw_vads, decoded):
            times = seq.available_at_s
            if args.decision_phase_ms == 128:
                decision_ends = np.arange(2048, len(wave)+1, 2560, dtype=np.int64)
                np.testing.assert_array_equal(times, decision_ends/16000)
                vad, energy = inputs_at_decisions(wave, raw, decision_ends)
                gate = vad if args.gate == 'mean' else raw[decision_ends//512-1]
            else:
                n = len(wave)//2560
                vad = raw.reshape(n, 5, 2).mean(axis=1)
                gate = vad if args.gate == 'mean' else raw.reshape(n, 5, 2)[:, -1]
                energy = np.log(np.sqrt((wave.reshape(n, 2560, 2)**2).mean(axis=1))+1e-7)[..., None]
            record = {'id': cid, 'x': speaker_features(seq.features.astype(np.float16), causal_history(times, vad), energy),
                      'times': times, 'vad': vad}
            probabilities = infer([record])[0]
            events = commit_events(times, gate, probabilities, op['threshold'], op['recommit_s'])
            prediction = ConversationPrediction(conversation_id=cid, speaker_1=SpeakerEvents(eot=events[1], interruption=[]),
                                                  speaker_2=SpeakerEvents(eot=events[2], interruption=[]))
            validate_event_times(prediction, duration)
            payload = {'prediction': prediction.model_dump(), 'duration_s': duration, 'audio_sha256': hashes}
            if cid in saved_rows:
                # Recompute partial groups with ORIGINAL batch membership. A changed
                # numerical execution must fail rather than silently mix outputs.
                for key, value in payload.items():
                    require_equal(saved_rows[cid][key], value, 'Recomputed conversation ' + cid)
                continue
            if args.dev_cache:
                _atomic_write(out / f'{cid}.npz', lambda file: np.savez_compressed(file, times=times, vad=vad,
                              gate_vad=gate, probabilities=probabilities))
                payload['dev_cache_sha256'] = sha(out / f'{cid}.npz')
            if args.dev_feature_cache:
                _atomic_write(out / f'{cid}.features.npz', lambda file: np.savez_compressed(file,
                    times=times, features=seq.features.astype(np.float16), vad=vad, extras=energy))
                payload['dev_features_sha256'] = sha(out / f'{cid}.features.npz')
            atomic_text(json.dumps({'identity': run_hash, 'payload': payload, 'payload_sha256': digest(payload)},
                                   sort_keys=True), out / 'conversations' / f'{cid}.json')
            saved_rows[cid] = payload
        print(json.dumps({'inferred': len(saved_rows), 'total': len(ids), 'split': args.split}), flush=True)
    submission = Submission(schema_version=1, predictions=[ConversationPrediction.model_validate(saved_rows[cid]['prediction']) for cid in ids])
    validate_coverage(submission, ids)
    atomic_text(submission.model_dump_json(indent=2), out / f'predictions-{args.split}.json')
    print('INFERENCE_COMPLETE', args.split, flush=True)


if __name__ == '__main__':
    main()
